from datetime import datetime
from app.models import AnalysisResult


def generate_markdown_report(analysis: AnalysisResult) -> str:
    s = analysis.executive_summary
    m = analysis.financial_metrics

    report = f"""# Due Diligence Report
**Generated:** {analysis.created_at.strftime("%Y-%m-%d %H:%M")}
**Document ID:** {analysis.document_id}

---

## Executive Summary

### Company Overview
{s.company_overview}

### Financial Health
{s.financial_health}

### Key Strengths
{chr(10).join(f"- {item}" for item in s.key_strengths) if s.key_strengths else "- Not identified"}

### Key Risks
{chr(10).join(f"- {item}" for item in s.key_risks) if s.key_risks else "- Not identified"}

### Growth Opportunities
{chr(10).join(f"- {item}" for item in s.growth_opportunities) if s.growth_opportunities else "- Not identified"}

### Recommendation
{s.recommendation}

**Confidence Score:** {s.confidence_score:.1%}

---

## Financial Metrics

| Metric | Value |
|--------|-------|
| Revenue | {m.revenue or "N/A"} |
| Revenue Growth | {m.revenue_growth or "N/A"} |
| Gross Margin | {m.gross_margin or "N/A"} |
| Operating Margin | {m.operating_margin or "N/A"} |
| Net Income | {m.net_income or "N/A"} |
| EBITDA | {m.ebitda or "N/A"} |
| Cash Position | {m.cash_position or "N/A"} |
| Debt Level | {m.debt_level or "N/A"} |
| Burn Rate | {m.burn_rate or "N/A"} |
| Runway | {m.runway_months or "N/A"} |
| ARR | {m.arr or "N/A"} |
| MRR | {m.mrr or "N/A"} |

---

## Risk Assessment

"""
    if analysis.risks:
        for i, risk in enumerate(analysis.risks, 1):
            severity_emoji = {"low": "🟢", "medium": "🟡", "high": "🟠", "critical": "🔴"}.get(risk.severity.value, "⚪")
            report += f"""### {i}. {severity_emoji} {risk.title}
**Category:** {risk.category.value.title()}
**Severity:** {risk.severity.value.upper()}

{risk.description}

"""
            if risk.evidence:
                report += "**Evidence:**\n"
                for ev in risk.evidence:
                    report += f'> "{ev.text}" *(trust: {ev.trust_level})*\n'
                report += "\n"
            report += f"**Recommendation:** {risk.recommendation}\n\n---\n\n"
    else:
        report += "No significant risks identified.\n\n---\n\n"

    report += f"""
## Appendix

- **Chunks analyzed:** {analysis.metadata.get('chunk_count', 'N/A')}
- **Context length:** {analysis.metadata.get('context_length', 'N/A')} chars
- **Analysis ID:** {analysis.id}

---

*This report was generated by AI Due Diligence Copilot. All findings should be verified by a qualified professional.*
"""
    return report


def generate_html_report(analysis: AnalysisResult) -> str:
    markdown = generate_markdown_report(analysis)
